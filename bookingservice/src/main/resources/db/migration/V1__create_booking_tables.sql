CREATE TABLE IF NOT EXISTS flight_inventory (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  flight_id VARCHAR(255) NOT NULL UNIQUE,
  seats_available INT NOT NULL,
  price DECIMAL(12,2) NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS booking (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  booking_uid VARCHAR(64) NOT NULL UNIQUE,
  user_id VARCHAR(128) NOT NULL,
  flight_id VARCHAR(255) NOT NULL,
  seats INT NOT NULL,
  status VARCHAR(32) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  idempotency_key VARCHAR(128),
  CONSTRAINT fk_flight FOREIGN KEY (flight_id) REFERENCES flight_inventory(flight_id)
) ENGINE=InnoDB;

CREATE INDEX idx_booking_idempotency ON booking(idempotency_key);
